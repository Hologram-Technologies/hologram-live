// Vendors the Hologram brand kit at pinned commits and generates web/src/tokens.css from its DTCG tokens.
// Nothing in the product CSS may define a color, size, space or radius: it all comes from here.
//
//   node apps/model-hub/web/scripts/vendor-kit.mjs [path to hologram-brand-kit clone]
//
// KIT_REV    develop, the kit's source of truth.
// SUCCESS_REV  open PR #1 (brand/close-token-gaps); only --success, --success-foreground and
//              --muted-foreground-subtle are taken from it until it merges.

import { execFileSync } from "node:child_process";
import { cp, mkdir, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const KIT_REV = "bce3bdf59de120e125754bfaef437d18aca14673";
const SUCCESS_REV = "d98a45d88e47deba3aff17b4a4449b40700fca98";
const SITE = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(SITE, "vendor", "hologram-brand-kit");
const clone = process.argv[2];
if (!clone) throw new Error("usage: node apps/model-hub/web/scripts/vendor-kit.mjs <path to a hologram-brand-kit clone>");

const show = (rev, path, encoding = "utf8") => execFileSync("git", ["-C", clone, "show", `${rev}:${path}`], { encoding, maxBuffer: 64 << 20 });

await mkdir(join(OUT, "fonts"), { recursive: true });
await mkdir(join(OUT, "logos"), { recursive: true });

const warm = show(KIT_REV, "brand/css/hologram-warm.css");
const tokens = JSON.parse(show(KIT_REV, "brand/tokens/hologram-tokens.json"));
await writeFile(join(OUT, "hologram-warm.css"), warm);
await writeFile(join(OUT, "hologram-tokens.json"), JSON.stringify(tokens, null, 2));

// Gap tokens from PR #1, copied verbatim per selector.
const pr = show(SUCCESS_REV, "brand/css/hologram-warm.css");
const gap = [];
for (const selector of [":root", ".dark"]) {
  const block = pr.match(new RegExp(`${selector.replace(".", "\\.")} \\{([^}]*)\\}`))[1];
  const lines = block.split("\n").filter((l) => /--(success|success-foreground|muted-foreground-subtle):/.test(l));
  if (lines.length !== 3) throw new Error(`PR #1 ${selector}: expected 3 gap tokens, found ${lines.length}`);
  gap.push(`${selector} {\n${lines.join("\n")}\n}`);
}
await writeFile(join(OUT, "hologram-gap-tokens.css"), `/* hologram-brand-kit PR #1 @ ${SUCCESS_REV} (unmerged). Remove when it lands on develop. */\n${gap.join("\n")}\n`);

for (const f of ["Geist-Regular", "Geist-Medium", "GeistMono-Regular", "GeistMono-Medium", "Archivo-Medium"]) {
  await writeFile(join(OUT, "fonts", `${f}.woff2`), show(KIT_REV, `brand/fonts/web/${f}.woff2`, "buffer"));
}
for (const f of ["OFL.txt", "OFL-Archivo.txt"]) await writeFile(join(OUT, "fonts", f), show(KIT_REV, `brand/fonts/${f}`));
for (const [dir, f] of [["logomark", "Hologram_Logomark_White"], ["lockup", "Hologram_Lockup_White"], ["wordmark", "Hologram_Wordmark_White"], ["logomark", "Hologram_Logomark_Black"], ["wordmark", "Hologram_Wordmark_Black"]]) {
  await writeFile(join(OUT, "logos", `${f}.svg`), show(KIT_REV, `brand/logos/svg/${dir}/${f}.svg`));
}
await writeFile(join(OUT, "REV"), `develop ${KIT_REV}\npr-1 ${SUCCESS_REV}\n`);

// ---- tokens.css: the kit's scales as CSS variables
const g = tokens.global;
const v = (t) => t.$value ?? t.value;
const lines = [];
for (const [k, t] of Object.entries(g.spacing)) lines.push(`  --space-${k}: ${v(t)};`);
for (const [k, t] of Object.entries(g.radius)) lines.push(`  --radius-${k}: ${v(t)};`);
for (const [k, t] of Object.entries(g.font.size)) lines.push(`  --text-${k}: ${v(t)};`);
for (const [k, t] of Object.entries(g.font.weight)) lines.push(`  --weight-${k}: ${v(t)};`);
for (const [k, t] of Object.entries(g.font.tracking)) lines.push(`  --tracking-${k}: ${v(t)};`);

const faces = [
  ["Geist", "Geist-Regular", 400], ["Geist", "Geist-Medium", 500],
  ["Geist Mono", "GeistMono-Regular", 400], ["Geist Mono", "GeistMono-Medium", 500],
  ["Archivo", "Archivo-Medium", 500],
].map(([family, file, weight]) => `@font-face { font-family: "${family}"; src: url("fonts/${file}.woff2") format("woff2"); font-weight: ${weight}; font-display: swap; }`);

await writeFile(join(SITE, "src", "tokens.css"), `/* Generated by apps/model-hub/web/scripts/vendor-kit.mjs from hologram-brand-kit @ ${KIT_REV}. Do not edit. */
${faces.join("\n")}

:root {
${lines.join("\n")}
}
`);
console.log(`vendored kit ${KIT_REV.slice(0, 9)} + PR #1 gap tokens ${SUCCESS_REV.slice(0, 9)}; tokens.css: ${lines.length} scale tokens`);
